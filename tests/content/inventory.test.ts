test("locks the complete ordered 97-page curriculum inventory", () => {
  const manifest = loadManifest("data/content-manifest.yml")
  const expectedModuleCounts = [6, 8, 12, 12, 8, 11, 23, 7, 5, 5]
  const expectedDirectoryCounts = [5, 8, 12, 12, 8, 11, 23, 7, 5, 5]

  assert.equal(manifest.pages.length, 97, "manifest must contain exactly 97 pages")
  assert.equal(
    manifest.modules.reduce((total, module) => total + module.target, 0),
    97,
    "module targets must total 97",
  )
  assert.deepEqual(
    manifest.modules.map(
      (module) => manifest.pages.filter((page) => page.module === module.id).length,
    ),
    expectedModuleCounts,
    "manifest page counts must match module targets in manifest order",
  )

  const typeCounts = { lesson: 0, index: 0, path: 0, glossary: 0 }
  for (const page of manifest.pages) {
    typeCounts[page.type] += 1
  }
  assert.deepEqual(typeCounts, { lesson: 87, index: 6, path: 3, glossary: 1 })
  assert.ok(
    manifest.pages.every((page) => page.required === true),
    "every page is required",
  )

  for (const field of ["id", "title", "file", "permalink"] as const) {
    assert.equal(new Set(manifest.pages.map((page) => page[field])).size, 97, `${field} is unique`)
  }
  assert.ok(
    manifest.pages.every((page) => /^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(page.id)),
    "every page id is lowercase kebab-case",
  )

  const moduleDirectories = new Map(manifest.modules.map((module) => [module.id, module.directory]))
  for (const page of manifest.pages) {
    assert.ok(!page.file.startsWith("templates/"), `${page.id} must not list a template`)
    if (page.id === "home") {
      assert.equal(page.file, "index.md", "home is the sole content-root file exception")
      continue
    }

    const expectedDirectory = moduleDirectories.get(page.module)
    assert.equal(page.file.split("/").length, 2, `${page.id} must be directly under its module`)
    assert.ok(
      expectedDirectory !== undefined && page.file.startsWith(`${expectedDirectory}/`),
      `${page.id} must be directly under ${expectedDirectory}`,
    )
  }
  assert.deepEqual(
    manifest.modules.map(
      (module) =>
        manifest.pages.filter((page) => page.file.startsWith(`${module.directory}/`)).length,
    ),
    expectedDirectoryCounts,
    "directory counts must match the canonical projection",
  )
  assert.equal(manifest.pages.find((page) => page.id === "how-to-use")?.type, "index")

  assert.deepEqual(manifest.modules, expectedModules)
  assert.deepEqual(manifest.pages, expectedPages)
})
